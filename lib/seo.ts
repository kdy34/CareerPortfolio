import type { Metadata } from "next";
import { profile } from "@/content";

/** The domain in content/en/site.ts wins; the environment variable is only a fallback. */
export const siteUrl = (profile.siteUrl || process.env.NEXT_PUBLIC_SITE_URL || "").replace(/\/$/, "") || undefined;
/** Indexing stays off until you set NEXT_PUBLIC_SITE_INDEXABLE=true at launch. */
export const indexable = process.env.NEXT_PUBLIC_SITE_INDEXABLE === "true";

export const siteTitle = `${profile.name} · AI Engineering, Data Science & Cloud`;
export const siteDescription =
  "Kutay Deniz Yazicioglu is an AI Engineering graduate student in the Washington, DC area who builds machine learning and LLM applications with data pipelines, APIs, and cloud software.";

/** The site-wide share image generated by app/opengraph-image.tsx. Resolved to an absolute URL through metadataBase. */
export const shareImage = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: `${profile.name}, AI Engineering and Data Science`,
};

/**
 * A page-level `openGraph` or `twitter` object replaces the root layout's object instead of merging with it,
 * so every page repeats the shared fields here. Without this, subpages lose og:image and share without a preview.
 */
export const openGraphBase = { type: "website" as const, siteName: profile.name, locale: "en_US", images: [shareImage] };
export const twitterBase = { card: "summary_large_image" as const, images: [shareImage] };

export function pageMeta(title: string, description: string, path: string): Metadata {
  return {
    title,
    description,
    alternates: siteUrl ? { canonical: path } : undefined,
    openGraph: { ...openGraphBase, title: `${title} · ${profile.name}`, description, url: path },
    twitter: { ...twitterBase, title: `${title} · ${profile.name}`, description },
  };
}
